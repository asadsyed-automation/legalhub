/**
 * Retrieves the portrait photo URL for an advocate.
 * Checks advocate object, email, name, or hashes to a dignified portrait.
 *
 * @param {object|string} advocate - Advocate object, email, or name
 * @returns {string} Portrait URL
 */
export const getAdvocatePhoto = (advocate) => {
  if (!advocate) return null;

  // 1. Direct photo url on advocate record
  if (typeof advocate === 'object') {
    if (advocate.profilePictureUrl) return advocate.profilePictureUrl;
    if (advocate.avatarUrl) return advocate.avatarUrl;
    if (advocate.photoUrl) return advocate.photoUrl;

    // Check by email
    if (advocate.email && ADVOCATE_PHOTOS[advocate.email]) {
      return ADVOCATE_PHOTOS[advocate.email];
    }

    // Check by name
    if (advocate.name && ADVOCATE_PHOTOS[advocate.name]) {
      return ADVOCATE_PHOTOS[advocate.name];
    }

    // Hash by ID or Name
    const key = advocate.id || advocate.name || 'advocate';
    let hash = 0;
    for (let i = 0; i < key.length; i++) {
      hash = key.charCodeAt(i) + ((hash << 5) - hash);
    }
    const index = Math.abs(hash) % PORTRAIT_POOL.length;
    return PORTRAIT_POOL[index];
  }

  // 2. Direct string key (name or email)
  if (typeof advocate === 'string') {
    if (ADVOCATE_PHOTOS[advocate]) {
      return ADVOCATE_PHOTOS[advocate];
    }
    let hash = 0;
    for (let i = 0; i < advocate.length; i++) {
      hash = advocate.charCodeAt(i) + ((hash << 5) - hash);
    }
    const index = Math.abs(hash) % PORTRAIT_POOL.length;
    return PORTRAIT_POOL[index];
  }

  return null;
};

export default getAdvocatePhoto;

